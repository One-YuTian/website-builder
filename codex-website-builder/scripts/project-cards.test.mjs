import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, appendFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawn } from 'node:child_process';
import { DatabaseSync } from 'node:sqlite';
import { chromium } from '@playwright/test';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';

const root = await mkdtemp(join(tmpdir(), 'project-cards-'));
const env = { ...process.env, CODEX_HOME:join(root,'codex'), CODEX_THREAD_ID:'cards-thread', WEBSITE_BUILDER_DATA_DIR:root, WEBSITE_BUILDER_PROJECT_ROOT:join(root,'project'), WEBSITE_BUILDER_SKILL_ROOT:resolve('skills/website-builder') };
const client = new Client({ name:'cards-test',version:'1' });
const call = async (name,args) => client.callTool({name,arguments:args});
const json = async (name,args) => { const result=await call(name,args);assert.ok(!result.isError,JSON.stringify(result));return JSON.parse(result.content[0].text); };
const manage = args => json('website_projects',{panel_id:'cards-panel',thread_id:'cards-thread',...args});
let browser,host,db;
try {
  await mkdir(env.CODEX_HOME,{recursive:true});
  const rollout=join(env.CODEX_HOME,'test-rollout.jsonl');
  const lifecycle=type=>JSON.stringify({type:'event_msg',payload:{type,turn_id:'root-turn',root_turn_id:'root-turn'}})+'\n';
  await writeFile(rollout,lifecycle('task_started'));
  const hostState=new DatabaseSync(join(env.CODEX_HOME,'state_5.sqlite'));
  hostState.exec('CREATE TABLE threads (id TEXT PRIMARY KEY, rollout_path TEXT)');
  hostState.prepare('INSERT INTO threads VALUES (?,?)').run('cards-thread',rollout);hostState.close();
  await client.connect(new StdioClientTransport({command:process.execPath,args:[resolve('dist/server/index.js')],env}));
  const state=await json('website_project',{thread_id:'cards-thread',name:'Casa Sol',brand:'Casa Sol',country:'BR',language:'pt-BR',categories:['家居','生活用品'],pages:[{path:'index.html',title:'Home'}]});
  const ids={thread_id:state.thread_id,project_id:state.project_id};
  const card=async()=> (await manage({action:'list'})).projects.find(p=>p.id===state.project_id);
  assert.equal((await card()).displayName,'巴西 · 葡萄牙语｜家居与生活用品');
  assert.equal((await card()).status,'pending');
  await json('website_project',{action:'begin',...ids,paths:['index.html']});
  assert.equal((await card()).status,'generating');
  const blocked=await call('website_projects',{action:'delete',panel_id:'cards-panel',...ids});
  assert.ok(blocked.isError);assert.match(JSON.stringify(blocked),/暂不可删除/);
  await json('website_write',{...ids,files:[{path:'index.html',content:'<!doctype html><html><body><h1>Casa Sol</h1></body></html>'}]});
  assert.equal((await card()).status,'completed');
  await json('website_project',{action:'begin',...ids,paths:['index.html']});
  assert.equal((await card()).status,'modifying');
  // Expired generation lease becomes failed and can be retried.
  db=new DatabaseSync(join(root,'db/website-builder.sqlite'));
  const row=db.prepare('SELECT data FROM projects WHERE id=?').get(state.project_id);
  const old=JSON.parse(row.data);old.updatedAt='2020-01-01T00:00:00Z';
  db.prepare('UPDATE projects SET data=? WHERE id=?').run(JSON.stringify(old),state.project_id);
  assert.equal((await card()).status,'failed');
  await json('website_project',{action:'begin',...ids,paths:['index.html']});
  assert.equal((await card()).status,'modifying');
  await json('website_project',{action:'finish',...ids,paths:['index.html']});
  await json('website_images',{...ids,action:'begin',path:'banner1.png',name:'Banner'});
  assert.equal((await card()).deletable,false);
  await json('website_images',{...ids,action:'fail',path:'banner1.png',error:'Test failure'});
  assert.equal((await card()).status,'failed');
  // UI shows the title/brand/time and replaces deletion while running.
  host=spawn(process.execPath,['dist/server/index.js','--preview'],{env,stdio:['ignore','pipe','pipe']});
  const url=await new Promise((resolve,reject)=>{host.stdout.once('data',d=>resolve(d.toString().trim()));host.once('error',reject);});
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({timezoneId:'Asia/Shanghai',viewport:{width:1440,height:900}});
  await page.goto(url);
  await page.getByRole('button',{name:'返回主界面',exact:true}).click();
  const element=page.locator(`[data-project-id="${state.project_id}"]`);
  await element.waitFor();assert.match(await element.innerText(),/巴西 · 葡萄牙语｜家居与生活用品/);
  assert.match(await element.locator('time').innerText(),/^\d{4}年\d{2}月\d{2}日 \d{2}:\d{2}/);
  assert.ok(!(await element.innerText()).includes('待确定'));
  assert.ok(!(await element.innerText()).includes('更新于'));
  assert.equal(await element.locator('strong').evaluate(n=>getComputedStyle(n).fontWeight),'400');
  const deleteBox=await element.locator('.project-delete').boundingBox();
  const deleteIcon=await element.locator('.project-delete svg').evaluate(n=>({width:getComputedStyle(n).width,height:getComputedStyle(n).height}));
  await json('website_project',{action:'begin',...ids,paths:['index.html']});
  await element.getByRole('status',{name:'修改中'}).waitFor({timeout:10000});
  assert.equal(await element.getByRole('status',{name:'修改中'}).innerText(),'');
  assert.equal(await element.locator('.project-status-spinner').count(),1);
  assert.equal(await element.locator('.project-delete').count(),0);
  const spinnerBox=await element.locator('.project-running').boundingBox();
  const spinnerIcon=await element.locator('.project-status-spinner').evaluate(n=>({width:getComputedStyle(n).width,height:getComputedStyle(n).height}));
  for(const key of ['x','y','width','height'])assert.ok(Math.abs(deleteBox[key]-spinnerBox[key])<1,`same action position/size: ${key}`);
  for(const key of ['width','height'])assert.equal(spinnerIcon[key],deleteIcon[key],'spinner and trash have matching dimensions');
  await appendFile(rollout,lifecycle('turn_aborted'));
  await page.waitForFunction(id=>!!document.querySelector(`[data-project-id="${id}"] .project-delete`),state.project_id,{timeout:10000});
  assert.equal((await card()).status,'paused','manual pause overrides still-active leases');
  assert.equal((await card()).deletable,true);
  assert.equal(await element.locator('.project-status-spinner').count(),0);
  await appendFile(rollout,lifecycle('task_started'));
  await element.locator('.project-status-spinner').waitFor({timeout:10000});
  assert.equal((await card()).status,'modifying','resume restores running state');
  await mkdir('artifacts',{recursive:true});await page.screenshot({path:'artifacts/project-cards.png'});
  for(const width of [375,768]){await page.setViewportSize({width,height:900});await page.screenshot({path:`artifacts/project-cards-${width}.png`});assert.ok(await element.locator('time').evaluate(n=>n.scrollWidth<=n.clientWidth+1));}
  await json('website_project',{action:'finish',...ids,paths:['index.html']});
  // Remove the failed image fixture to verify the completed card presentation.
  db.prepare('DELETE FROM image_tasks WHERE project_id=?').run(state.project_id);
  db.prepare('DELETE FROM project_activity WHERE project_id=?').run(state.project_id);
  await page.waitForFunction(id=>!document.querySelector(`[data-project-id="${id}"] .project-status`),state.project_id);
  await manage({action:'delete',project_id:state.project_id});
  assert.ok(!(await manage({action:'list'})).projects.some(p=>p.id===state.project_id));
  const firstBuild=await json('website_project',{thread_id:'two-page-build',pages:[{path:'index.html',title:'Home'},{path:'shop.html',title:'Shop'}]});
  const other={thread_id:firstBuild.thread_id,project_id:firstBuild.project_id};
  await json('website_project',{action:'begin',...other,paths:['index.html','shop.html']});
  await json('website_write',{...other,files:[{path:'index.html',content:'<!doctype html><html><body>Home</body></html>'}]});
  const partial=(await manage({action:'list'})).projects.find(p=>p.id===firstBuild.project_id);
  assert.equal(partial.status,'generating','first build stays generating until the initial site completes');
  console.log('PASS: structured title, pending/generating/modifying/completed/failed, expiry recovery, image tasks, backend deletion guard, real card rendering and local timestamp');
} finally { db?.close();await browser?.close();host?.kill();await client.close(); }
