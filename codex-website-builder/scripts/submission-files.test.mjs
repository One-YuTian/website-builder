import assert from 'node:assert/strict';
import {mkdtemp,readFile,readdir,stat} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
const root=await mkdtemp(join(tmpdir(),'website-submission-files-'));
const env={...process.env,CODEX_THREAD_ID:'upload-source',WEBSITE_BUILDER_DATA_DIR:root};delete env.WEBSITE_BUILDER_PROJECT_ROOT;
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
let client;
const connect=async()=>{client=new Client({name:'upload-test',version:'1'});await client.connect(new StdioClientTransport({command:process.execPath,args:[resolve('dist/server/index.js')],env}));};
const raw=args=>client.callTool({name:'website_projects',arguments:args});
const call=async args=>{const result=await raw(args);assert.ok(!result.isError,JSON.stringify(result));return JSON.parse(result.content[0].text);};
const panel={panel_id:'upload-test-panel',request_id:'upload-test-request'};
const first=Buffer.from('[{"id":"1","name":"Original","category":"Home","price":12}]');
const second=Buffer.from(JSON.stringify({products:[{id:'2',name:'Second',category:'Home',price:13,description:'完整正文'.repeat(50000)}]}));
const upload=(upload_id,bytes,offset,chunk,final=false,file_name='products.json')=>({...panel,action:'upload',upload_id,file_name,mime_type:'application/json',total_size:bytes.length,sha256:hash(bytes),offset,chunk:chunk.toString('base64'),final});
try{
 await connect();
 await call({...panel,action:'home'});
 await call({...panel,action:'submission',submission_start:true,file_count:2,requirement:'Upload every attachment'});
 const before=(await call({action:'list'})).projects.length;
 const firstArgs=upload('first-upload-file',first,0,first,true);
 await Promise.all([call(firstArgs),call(firstArgs)]);
 assert.ok((await raw({...panel,action:'create',thread_id:'upload-destination'})).isError,'incomplete attachments must block creation');
 assert.equal((await call({action:'list'})).projects.length,before);
 assert.ok((await raw({...firstArgs,request_id:'unrelated-request'})).isError);
 const chunk=second.subarray(0,192*1024);
 await call(upload('second-upload-file',second,0,chunk));
 assert.ok((await raw(upload('second-upload-file',second,chunk.length+1,Buffer.from('bad')))).isError);
 const retry=await call(upload('second-upload-file',second,0,chunk));assert.equal(retry.received,chunk.length,'retry must not duplicate bytes');
 await client.close();await connect();
 for(let offset=chunk.length;offset<second.length;offset+=192*1024){const part=second.subarray(offset,offset+192*1024);await call(upload('second-upload-file',second,offset,part,offset+part.length===second.length));}
 const project=await call({...panel,action:'create',thread_id:'upload-destination',name:'Persistent uploads'});
 assert.equal(project.files.length,2);assert.notEqual(project.files[0].path,project.files[1].path);
 assert.deepEqual((await Promise.all(project.files.map(async item=>hash(await readFile(item.path))))).sort(),[hash(first),hash(second)].sort());
 assert.equal((await readdir(project.files_directory)).length,2);
 await client.close();await connect();
 const repeated=await call({...panel,action:'create',thread_id:'upload-destination'});assert.equal(repeated.project_id,project.project_id);assert.equal(repeated.files.length,2);
 const listed=await call({action:'resources',panel_id:'upload-dest-panel',thread_id:'upload-destination',project_id:project.project_id});assert.equal(listed.resources.length,2);
 const emptyPanel={panel_id:'empty-upload-panel',request_id:'empty-upload-request'};
 await call({...emptyPanel,action:'submission',submission_start:true,file_count:1});
 await call({...upload('empty-upload-file',Buffer.alloc(0),0,Buffer.alloc(0),true,'empty.txt'),...emptyPanel});
 const empty=await call({...emptyPanel,action:'create',thread_id:'empty-upload-thread'});assert.equal((await stat(empty.files[0].path)).size,0);
 const badPanel={panel_id:'bad-upload-panel',request_id:'bad-upload-request'};
 await call({...badPanel,action:'submission',submission_start:true,file_count:1});
 assert.ok((await raw({...firstArgs,...badPanel,sha256:'0'.repeat(64)})).isError,'bad digest never becomes a ready attachment');
 assert.ok((await raw({...badPanel,action:'create',thread_id:'bad-upload-thread'})).isError);
 await call({...badPanel,action:'submission',cancel:true});
 assert.ok((await raw({...firstArgs,...badPanel})).isError,'cancelled requests reject further upload');
 console.log('PASS: bounded chunk upload, concurrent retries, incomplete/hash rejection, restart recovery, collision protection, resource registration and empty-file preservation');
}finally{await client?.close();}
